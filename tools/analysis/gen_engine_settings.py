"""Generate src/Slrr.Engine.Parts/RawEdit/EngineSettings.g.cs from docs/research/rawedit-addresses.tsv.

Usage: python3 -I tools/analysis/gen_engine_settings.py [repo_root]

The TSV is the single source of truth for the RawEdit address map (docs/research/rawedit.md section 3/4). Every row
becomes one typed property of a settings group plus one RawAddressMap entry. Nothing here touches game binaries.
"""

import csv
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..")
tsv = os.path.join(root, "docs", "research", "rawedit-addresses.tsv")
out = os.path.join(root, "src", "Slrr.Engine.Parts", "RawEdit", "EngineSettings.g.cs")

rows = list(csv.DictReader(open(tsv, encoding="utf-8"), delimiter="\t"))


def num(text, kind):
    text = (text or "").strip()
    if not re.fullmatch(r"-?[0-9.]+(e[+-]?[0-9]+)?", text):
        return None
    return int(float(text)) if kind == "int" else float(text)


def lit(v, kind):
    if kind == "bool":
        return "true" if v else "false"
    if kind == "int":
        return str(int(v))
    s = repr(float(v))
    return s + "f"


groups = {}
entries = []
for r in rows:
    prop = r["proposed_property"]
    raw_kind = r["type"]  # int / float: the 32-bit cell type in the exe
    ptype = r["prop_type"]
    kind = "bool" if ptype.startswith("bool") else ("float" if raw_kind == "float" else "int")
    readonly = "read-only" in ptype
    derived = prop.startswith("(derived")
    gi = num(r["gi_default"], raw_kind)
    redline = num(r["redline_value"], raw_kind)
    config_backed = bool(r["config_key"])
    gi = gi if gi is not None else 0
    # Vanilla preset: the Redline file value for config-backed globals; mod variables did not exist there, the GI
    # default (= the mod's neutral setting) is used instead (rawedit.md section 4 rule 3; choice documented as a guess).
    vanilla = redline if (config_backed and redline is not None) else gi
    if derived:
        entries.append(dict(r=r, group="Damage", name="BodyDeformationMultMinus", kind=kind, derived=True, readonly=True))
        continue
    group, _, rest = prop.partition(".")
    name = rest.replace(".", "")
    m = re.match(r"(.*)\[(\d)\]$", name)
    if m:
        name = m.group(1) + str(int(m.group(2)) + 1)
    groups.setdefault(group, []).append(dict(name=name, kind=kind, gi=gi, vanilla=vanilla, readonly=readonly, r=r))
    entries.append(dict(r=r, group=group, name=name, kind=kind, derived=False, readonly=readonly))

cs = []
w = cs.append
w("// <auto-generated> by tools/analysis/gen_engine_settings.py from docs/research/rawedit-addresses.tsv; do not edit.")
w("namespace Slrr.Engine.Parts.RawEdit;")
w("")
ctype = {"int": "int", "float": "float", "bool": "bool"}
for g, props in groups.items():
    w(f"/// <summary>RawEdit settings group <c>{g}</c> ({len(props)} values).</summary>")
    w(f"public sealed partial class {g}Settings")
    w("{")
    for p in props:
        r = p["r"]
        conf = r["confidence"]
        key = f", config key <c>{r['config_key']}</c>" if r["config_key"] else ""
        meaning = (r["meaning"] or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        ro = " Read-only for scripts (RawEdit writes are ignored); the host updates it." if p["readonly"] else ""
        w(f"    /// <summary><c>{r['name']}</c> at {r['address']} ({conf}{key}). {meaning}{ro}</summary>")
        w(f"    public {ctype[p['kind']]} {p['name']} {{ get; set; }}")
        w("")
    w("    internal void ApplyPreset(bool vanilla)")
    w("    {")
    for p in props:
        w(f"        {p['name']} = vanilla ? {lit(p['vanilla'], p['kind'])} : {lit(p['gi'], p['kind'])};")
    w("    }")
    w("}")
    w("")

w("/// <summary>The 69 RawEdit addresses, in TSV order.</summary>")
w("public static partial class RawAddressMap")
w("{")
w("    private static RawAddressEntry[] Build() =>")
w("    [")
for e in entries:
    r = e["r"]
    addr = r["address"]
    t = "RawCellType.Float" if r["type"] == "float" else "RawCellType.Int"
    g, n = e["group"], e["name"]
    if e["derived"]:
        get = "s => -s.Damage.BodyDeformationMult"
        sett = "null"
    else:
        getv = f"s.{g}.{n}"
        if e["kind"] == "bool":
            get = f"s => {getv} ? 1 : 0"
            sett = f"(s, v) => {getv} = v != 0"
        elif e["kind"] == "int":
            get = f"s => {getv}"
            sett = f"(s, v) => {getv} = (int)v"
        else:
            get = f"s => {getv}"
            sett = f"(s, v) => {getv} = (float)v"
        if e["readonly"]:
            sett = "null"
    w(f"        new(0x{int(addr, 16):08x}u, \"{r['name']}\", \"{g}.{n}\", {t}, '{r['confidence']}', {get}, {sett}),")
w("    ];")
w("}")

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(cs) + "\n")
print(f"wrote {out}: {len(entries)} entries, {len(groups)} groups")
