using System.Globalization;
using System.Reflection;
using System.Text.Json;
using Slrr.Core;
using Slrr.Formats.Cfg;

namespace Slrr.Formats.CfgSchema;

/// <summary>Observed token shapes. <c>Int</c> is accepted wherever <c>Float</c> is allowed.</summary>
public static class CfgArgTypes
{
    public static string Classify(string t)
    {
        if (t.Length > 2 && t[0] == '0' && (t[1] is 'x' or 'X') && t.Length <= 10 && t.AsSpan(2).ToString().All(Uri.IsHexDigit))
        {
            return "hex";
        }

        if (IsInt(t))
        {
            return "int";
        }

        if (IsFloat(t))
        {
            return "float";
        }

        if (t.Contains(','))
        {
            var parts = t.Split(',');
            if (parts.Length > 1 && parts.All(p => p.Length == 0 || IsInt(p) || IsFloat(p)))
            {
                return "vector";
            }
        }

        var colon = t.IndexOf(':');
        if (colon > 0 && (IsInt(t[..colon]) || IsFloat(t[..colon])) && (IsInt(t[(colon + 1)..]) || IsFloat(t[(colon + 1)..])))
        {
            return "pair";
        }

        if (t.Contains('\\') || t.Contains('/') || HasExtension(t))
        {
            return "path";
        }

        return "word";
    }

    private static bool HasExtension(string t)
    {
        var dot = t.LastIndexOf('.');
        var n = t.Length - dot - 1;
        return dot >= 0 && n is >= 2 and <= 5 && t.AsSpan(dot + 1).ToString().All(char.IsAsciiLetterOrDigit);
    }

    private static bool IsInt(string t)
    {
        var s = t.Length > 0 && t[0] is '+' or '-' ? t[1..] : t;
        return s.Length > 0 && s.All(char.IsAsciiDigit);
    }

    private static bool IsFloat(string t)
    {
        // mirrors ^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$
        var i = 0;
        if (i < t.Length && t[i] is '+' or '-')
        {
            i++;
        }

        var digits = 0;
        while (i < t.Length && char.IsAsciiDigit(t[i]))
        {
            i++;
            digits++;
        }

        if (i < t.Length && t[i] == '.')
        {
            i++;
            while (i < t.Length && char.IsAsciiDigit(t[i]))
            {
                i++;
                digits++;
            }
        }

        if (digits == 0)
        {
            return false;
        }

        if (i < t.Length && t[i] is 'e' or 'E')
        {
            i++;
            if (i < t.Length && t[i] is '+' or '-')
            {
                i++;
            }

            var exp = 0;
            while (i < t.Length && char.IsAsciiDigit(t[i]))
            {
                i++;
                exp++;
            }

            if (exp == 0)
            {
                return false;
            }
        }

        return i == t.Length && double.TryParse(t, NumberStyles.Float, CultureInfo.InvariantCulture, out _);
    }
}

/// <summary>Argument schema of one cfg keyword, generated by <c>tools/schema/gen_cfg_schema.py</c>.</summary>
public sealed record KeywordSchema(string Keyword, int Lines, int Files, int Min, int Max, IReadOnlyList<IReadOnlyList<string>> Args, bool Enforce);

/// <summary>
/// Data-driven per-keyword argument rules (embedded <c>cfg-schema.json</c>). Emits
/// CFG300 (argument count outside the observed range) and CFG301 (argument shape never observed at that position).
/// </summary>
public sealed class CfgArgSchemas
{
    private static readonly Lazy<CfgArgSchemas> DefaultInstance = new(LoadEmbedded);

    private readonly Dictionary<string, KeywordSchema> _byKeyword;

    public CfgArgSchemas(IEnumerable<KeywordSchema> schemas) =>
        _byKeyword = schemas.ToDictionary(s => s.Keyword, StringComparer.Ordinal);

    public static CfgArgSchemas Default => DefaultInstance.Value;

    public IReadOnlyCollection<KeywordSchema> Keywords => _byKeyword.Values;

    public KeywordSchema? Get(string keyword) => _byKeyword.GetValueOrDefault(keyword);

    public static CfgArgSchemas Parse(string json)
    {
        using var doc = JsonDocument.Parse(json);
        var list = new List<KeywordSchema>();
        foreach (var p in doc.RootElement.GetProperty("keywords").EnumerateObject())
        {
            var v = p.Value;
            var args = v.GetProperty("args").EnumerateArray()
                .Select(a => (IReadOnlyList<string>)a.EnumerateArray().Select(x => x.GetString()!).ToArray()).ToArray();
            list.Add(new(p.Name, v.GetProperty("lines").GetInt32(), v.GetProperty("files").GetInt32(),
                v.GetProperty("min").GetInt32(), v.GetProperty("max").GetInt32(), args, v.GetProperty("enforce").GetBoolean()));
        }

        return new CfgArgSchemas(list);
    }

    /// <summary>Checks one directive line (any kind; only <see cref="CfgLineKind.Directive"/> lines are checked).</summary>
    public IEnumerable<Diagnostic> Check(CfgLine line, string file)
    {
        if (line.Kind != CfgLineKind.Directive || line.Keyword is null || !_byKeyword.TryGetValue(line.Keyword, out var s) || !s.Enforce)
        {
            yield break;
        }

        var n = line.Args.Count;
        if (n < s.Min || n > s.Max)
        {
            var want = s.Min == s.Max ? $"{s.Min}" : $"{s.Min}..{s.Max}";
            yield return new(Severity.Warning, "CFG300", $"'{line.Keyword}' takes {want} argument(s) but has {n}", file, line.Number);
        }

        for (var i = 0; i < n && i < s.Args.Count; i++)
        {
            var type = CfgArgTypes.Classify(line.Args[i]);
            var allowed = s.Args[i];
            if (allowed.Contains(type) || (type == "int" && allowed.Contains("float")))
            {
                continue;
            }

            yield return new(Severity.Warning, "CFG301",
                $"'{line.Keyword}' argument {i + 1} '{line.Args[i]}' is {type}, expected {string.Join("/", allowed)}", file, line.Number);
        }
    }

    private static CfgArgSchemas LoadEmbedded()
    {
        var asm = typeof(CfgArgSchemas).Assembly;
        var name = asm.GetManifestResourceNames().Single(n => n.EndsWith("cfg-schema.json", StringComparison.Ordinal));
        using var s = asm.GetManifestResourceStream(name)!;
        using var r = new StreamReader(s);
        return Parse(r.ReadToEnd());
    }
}
